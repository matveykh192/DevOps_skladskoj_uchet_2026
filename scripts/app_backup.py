"""Backup the main Docker Compose warehouse DB; restore safely for verification.

Usage: python scripts/app_backup.py {backup|restore-check|restore-main}
The restore-main command is deliberately guarded and destructive.
"""

import argparse
import hashlib
import subprocess
import sys
import uuid
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BACKUPS = ROOT / "backups"
COMPOSE = ["docker", "compose", "-f", "docker-compose.yml"]
DB = "warehouse_db"
USER = "warehouse_user"
VERIFY_DB = "warehouse_restore_verify"
CONFIRMATION = "RESTORE_WAREHOUSE_DB"
LATEST = BACKUPS / "warehouse_db.dump"


def run(args, *, stdin=None, stdout=None, capture=False):
    return subprocess.run(
        args, cwd=ROOT, stdin=stdin, stdout=subprocess.PIPE if capture else stdout,
        check=True, text=False,
    )


def db_exec(*args):
    return COMPOSE + ["exec", "-T", "db", *args]


def check_target():
    # Refuse to operate against a renamed or repurposed DB service.
    out = run(db_exec("printenv", "POSTGRES_USER", "POSTGRES_DB"), capture=True).stdout.decode().splitlines()
    if out != [USER, DB]:
        raise RuntimeError(f"Unexpected main PostgreSQL service identification: {out!r}")
    result = run(db_exec("psql", "-X", "-At", "-v", "ON_ERROR_STOP=1", "-U", USER,
                         "-d", DB, "-c", "SELECT current_database()"), capture=True).stdout.decode().strip()
    if result != DB:
        raise RuntimeError("Incorrect main DB; refusing operation")


def container_id():
    """Resolve the running main DB container, never the isolated test stack."""
    value = run(COMPOSE + ["ps", "-q", "db"], capture=True).stdout.decode().strip()
    if not value or "\n" in value:
        raise RuntimeError("Main PostgreSQL container not found or ambiguous")
    return value


def temp_container_archive():
    return f"/tmp/warehouse_archive_{uuid.uuid4().hex}.dump"


def cleanup_container_archive(container_path):
    # Only ever delete an archive generated by this script inside /tmp.
    if not container_path.startswith("/tmp/warehouse_archive_") or not container_path.endswith(".dump"):
        raise RuntimeError("Unsafe temporary archive path")
    run(db_exec("rm", "-f", container_path))


def verify_archive(path):
    if not path.is_file() or path.stat().st_size < 100:
        raise RuntimeError(f"Missing or empty archive: {path}")
    with path.open("rb") as stream:
        if stream.read(5) != b"PGDMP":
            raise RuntimeError("Not a PostgreSQL custom-format archive")
    # Avoid streaming binary data through Docker CLI stdin on Windows.
    # Validate a copied file from within the Linux PostgreSQL container.
    tmp_container = temp_container_archive()
    try:
        run(["docker", "cp", str(path), f"{container_id()}:{tmp_container}"])
        run(db_exec("pg_restore", "-l", tmp_container), stdout=subprocess.DEVNULL)
    finally:
        cleanup_container_archive(tmp_container)
    return hashlib.sha256(path.read_bytes()).hexdigest()


def backup(*, output=None):
    BACKUPS.mkdir(exist_ok=True, parents=True)
    path = output or LATEST
    tmp = path.with_suffix(path.suffix + ".partial")
    tmp_container = temp_container_archive()
    try:
        run(db_exec("pg_dump", "-U", USER, "-d", DB, "-Fc", "--no-owner", "--no-acl", "-f", tmp_container))
        run(["docker", "cp", f"{container_id()}:{tmp_container}", str(tmp)])
        sha = verify_archive(tmp)
        tmp.replace(path)
    finally:
        tmp.unlink(missing_ok=True)
        cleanup_container_archive(tmp_container)
    print(f"MAIN BACKUP OK: {path} ({path.stat().st_size} bytes, sha256={sha})")
    return path


def sql(statement):
    run(db_exec("psql", "-X", "-v", "ON_ERROR_STOP=1", "-U", USER,
                "-d", "postgres", "-c", statement))


def verify_database(name):
    out = run(db_exec("psql", "-X", "-A", "-t", "-v", "ON_ERROR_STOP=1", "-U", USER,
                      "-d", name, "-c", "SELECT version_num FROM alembic_version"), capture=True)
    revision = out.stdout.decode().strip()
    if revision != "003_minimum_stock":
        raise RuntimeError(f"Unexpected restored revision: {revision!r}")
    out = run(db_exec("psql", "-X", "-A", "-t", "-v", "ON_ERROR_STOP=1", "-U", USER,
                      "-d", name, "-c", "SELECT count(*) FROM materials"), capture=True)
    print(f"RESTORED DB CHECK OK: revision={revision}, materials={out.stdout.decode().strip()}")


def recreate(name):
    if name not in (VERIFY_DB, DB):
        raise RuntimeError("Refusing unexpected restore destination")
    sql(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)')
    sql(f'CREATE DATABASE "{name}" OWNER "{USER}"')


def restore_to(name, archive):
    tmp_container = temp_container_archive()
    try:
        run(["docker", "cp", str(archive), f"{container_id()}:{tmp_container}"])
        run(db_exec("pg_restore", "-U", USER, "-d", name,
                    "--no-owner", "--no-acl", "--exit-on-error", tmp_container))
        verify_database(name)
    finally:
        cleanup_container_archive(tmp_container)


def restore_check(archive):
    print(f"RESTORE CHECK ONLY: recreating disposable {VERIFY_DB}; main {DB} is untouched")
    recreate(VERIFY_DB)
    try:
        restore_to(VERIFY_DB, archive)
        print("RESTORE CHECK PASSED: main archive restored to separate database")
    finally:
        # Keep the main database intact even if validation fails; clean only disposable DB.
        sql(f'DROP DATABASE IF EXISTS "{VERIFY_DB}" WITH (FORCE)')


def restore_main(archive, confirmation):
    if confirmation != CONFIRMATION:
        raise RuntimeError(f"Refusing main DB restore. Explicit --confirm {CONFIRMATION} required")
    # Always take a new, immutable pre-restore safety backup first.
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    safety = BACKUPS / f"warehouse_before_restore_{stamp}.dump"
    backup(output=safety)
    print("Stopping main application for destructive database restore...")
    run(COMPOSE + ["stop", "app"])
    print(f"SAFETY ARCHIVE: {safety}")
    print("Recreating the main database and restoring from the selected archive...")
    recreate(DB)
    restore_to(DB, archive)
    print("MAIN RESTORE OK. Restart the app with: docker compose up -d app")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("backup", "restore-check", "restore-main"))
    parser.add_argument("--archive", type=Path, default=LATEST, help="Archive for restore; default backups/warehouse_db.dump")
    parser.add_argument("--confirm", default="", help="Required only for destructive restore-main")
    args = parser.parse_args()
    check_target()
    if args.action == "backup":
        backup()
        return
    archive = args.archive.resolve()
    sha = verify_archive(archive)
    print(f"ARCHIVE VERIFIED: {archive}, sha256={sha}")
    if args.action == "restore-check":
        restore_check(archive)
    else:
        restore_main(archive, args.confirm)


if __name__ == "__main__":
    try:
        main()
    except (OSError, RuntimeError, subprocess.CalledProcessError) as exc:
        print(f"DATABASE BACKUP/RESTORE FAILED: {exc}", file=sys.stderr)
        sys.exit(1)
